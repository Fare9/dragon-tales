std::optional<dragon::ignil::Reg>
dragon::arm::ARMIGNILLifter::toReg(unsigned llvmReg) const {
  auto it = regMap_.find(llvmReg);
  return it == regMap_.end() ? std::nullopt : std::optional{it->second};
}

bool dragon::arm::ARMIGNILLifter::isZeroReg(const ignil::Reg &reg) const {
  // XZR/WZR share the same offset in armregisters.def, differing only in
  // width (64 vs 32), so offset alone identifies the zero register
  // regardless of which view is in use.
  return reg.offset == regXZR_.offset;
}

dragon::ignil::Temp
dragon::arm::ARMIGNILLifter::newTemp(std::uint32_t &tempId,
                                     ignil::Width width) const {
  return ignil::Temp{tempId++, width};
}

dragon::ignil::Block
dragon::arm::ARMIGNILLifter::liftBlock(const BasicBlock &block,
                                       const Graph &graph) const {
  ignil::Block result{block.startAddress()};
  std::uint32_t tempId = 0;

  for (const Instruction *insn: block.instructions()) {
    liftInstruction(*insn, result, tempId);
  }

  return result;
}

void dragon::arm::ARMIGNILLifter::liftInstruction(const Instruction &insn,
                                                  ignil::Block &out,
                                                  std::uint32_t &tempId) const {
  const auto *mc = insn.mcInst();
  if (!mc)
    return;

  unsigned opc = mc->getOpcode();
  std::uint64_t addr = insn.address();

  // First lift the move operations, in ARM we have a few different
  // move instructions (MOVZ, MOVN, MOVK) that we need to handle separately.
  if (opc == opMOVZWi_ || opc == opMOVZXi_)
    liftMovz(*mc, addr, out, tempId);
  else if (opc == opMOVNWi_ || opc == opMOVNXi_)
    liftMovn(*mc, addr, out, tempId);
  else if (opc == opMOVKWi_ || opc == opMOVKXi_)
    liftMovk(*mc, addr, out, tempId);
  // Generation of arithmetic and logic instructions, this is handled
  // by the liftAddSub and liftLogic functions, which handle all the different
  // variants of the instructions (register, immediate, and S-suffixed).
  else if (opc == opADDWrr_ || opc == opADDXrr_ || opc == opADDWri_ ||
           opc == opADDXri_ || opc == opADDWrs_ || opc == opADDXrs_)
    liftAddSub(*mc, addr, out, tempId);
  else if (opc == opSUBWrr_ || opc == opSUBXrr_ || opc == opSUBWri_ ||
           opc == opSUBXri_ || opc == opSUBWrs_ || opc == opSUBXrs_)
    liftAddSub(*mc, addr, out, tempId);
  else if (opc == opANDWrr_ || opc == opANDXrr_ || opc == opANDWri_ ||
           opc == opANDXri_ || opc == opANDWrs_ || opc == opANDXrs_)
    liftLogic(*mc, addr, out, tempId);
  else if (opc == opORRWrr_ || opc == opORRXrr_ || opc == opORRWri_ ||
           opc == opORRXri_ || opc == opORRWrs_ || opc == opORRXrs_)
    liftLogic(*mc, addr, out, tempId);
  else if (opc == opEORWrr_ || opc == opEORXrr_ || opc == opEORWri_ ||
           opc == opEORXri_ || opc == opEORWrs_ || opc == opEORXrs_)
    liftLogic(*mc, addr, out, tempId);
  // Load and store instructions, these are handled by the liftLoad and
  // liftStore functions, which handle all the different variants of the
  // instructions (immediate, register, pre/post-indexed).
  //
  // These must be explicit OR-chains, not opcode-number ranges: the op*_
  // fields are assigned whatever integer LLVM happened to give that opcode
  // during the constructor's scan, and LLVM's opcode numbering is neither
  // ordered by mnemonic nor contiguous within a family (e.g. LDRWui=4504 but
  // LDRSWui=4492 in this build - a range check silently matches nothing).
  else if (opc == opLDRWui_ || opc == opLDRXui_ || opc == opLDRBui_ ||
           opc == opLDRBBui_ || opc == opLDRHui_ || opc == opLDRHHui_ ||
           opc == opLDRSBWui_ || opc == opLDRSBXui_ || opc == opLDRSHWui_ ||
           opc == opLDRSHXui_ || opc == opLDRSWui_ || opc == opLDRWpre_ ||
           opc == opLDRWpost_ || opc == opLDRXpre_ || opc == opLDRXpost_)
    liftLoad(*mc, addr, out, tempId);
  else if (opc == opSTRWui_ || opc == opSTRXui_ || opc == opSTRBui_ ||
           opc == opSTRBBui_ || opc == opSTRHui_ || opc == opSTRHHui_ ||
           opc == opSTRWpre_ || opc == opSTRWpost_ || opc == opSTRXpre_ ||
           opc == opSTRXpost_)
    liftStore(*mc, addr, out, tempId);
  // When two registers are loaded or stored at once, we use the load/store pair
  // instructions, which are handled by the liftLoadPair and liftStorePair
  // functions.
  else if (opc == opLDPWi_ || opc == opLDPXi_ || opc == opLDPWpre_ ||
           opc == opLDPXpre_ || opc == opLDPWpost_ || opc == opLDPXpost_)
    liftLoadPair(*mc, addr, out, tempId);
  else if (opc == opSTPWi_ || opc == opSTPXi_ || opc == opSTPWpre_ ||
           opc == opSTPXpre_ || opc == opSTPWpost_ || opc == opSTPXpost_)
    liftStorePair(*mc, addr, out, tempId);
  // Similar to LEA instructions in x86, ADR and ADRP instructions are
  // used to compute addresses, and are handled by the liftAdr function.
  else if (opc == opADR_ || opc == opADRP_)
    liftAdr(*mc, addr, out, tempId);
  // Conditional branch family - must be checked before the generic
  // isBranch() fallback below, since Bcc/CBZ/CBNZ/TBZ/TBNZ are all
  // isBranch()==true but have operand shapes liftBranch does not expect.
  else if (opc == opBcc_)
    liftBcc(*mc, addr, out, tempId);
  else if (opc == opCBZW_ || opc == opCBZX_ || opc == opCBNZW_ ||
           opc == opCBNZX_)
    liftCbz(*mc, addr, out, tempId);
  else if (opc == opTBZW_ || opc == opTBZX_ || opc == opTBNZW_ ||
           opc == opTBNZX_)
    liftTbz(*mc, addr, out, tempId);
  else {
    const auto &desc = instrInfo_->get(opc);
    if (desc.isReturn())
      liftRet(*mc, addr, out, tempId);
    else if (desc.isCall())
      liftCall(*mc, addr, out, tempId);
    else if (desc.isBranch())
      liftBranch(*mc, addr, out, tempId);
  }
}

void dragon::arm::ARMIGNILLifter::liftMovz(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp) const {
  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftMovz in addr {:#x} no dst", addr);
    return;
  }
  auto imm = static_cast<std::uint64_t>(mc.getOperand(1).getImm());
  auto shift = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
  std::uint64_t value = imm << shift;

  if (isZeroReg(*dst))
    return;

  out.append(
          {ignil::Opcode::COPY, *dst, {ignil::Const{value, dst->width}}, addr});
}

void dragon::arm::ARMIGNILLifter::liftMovk(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp) const {
  // op[0] = dst, op[1] = dst again (tied - the pre-update value), op[2] =
  // 16-bit imm, op[3] = shift. Unlike MOVZ/MOVN, the pre-update value is a
  // runtime unknown, so this is a real read-modify-write, not a lift-time
  // constant.
  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftMovk in addr {:#x} no dst", addr);
    return;
  }

  auto imm = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
  auto shift = static_cast<std::uint64_t>(mc.getOperand(3).getImm());
  std::uint64_t clearMask = ~(0xFFFFULL << shift);
  std::uint64_t insertBits = imm << shift;

  if (isZeroReg(*dst))
    return;

  auto cleared = newTemp(tmp, dst->width);
  out.append({ignil::Opcode::AND,
              cleared,
              {*dst, ignil::Const{clearMask, dst->width}},
              addr});
  auto inserted = newTemp(tmp, dst->width);
  out.append({ignil::Opcode::OR,
              inserted,
              {cleared, ignil::Const{insertBits, dst->width}},
              addr});
  out.append({ignil::Opcode::COPY, *dst, {inserted}, addr});
}

void dragon::arm::ARMIGNILLifter::liftMovn(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp) const {
  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftMovn in addr {:#x} no dst", addr);
    return;
  }

  auto imm = static_cast<std::uint64_t>(mc.getOperand(1).getImm());
  auto shift = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
  std::uint64_t value = ~(imm << shift);

  if (isZeroReg(*dst))
    return;

  out.append(
          {ignil::Opcode::COPY, *dst, {ignil::Const{value, dst->width}}, addr});
}

void dragon::arm::ARMIGNILLifter::emitUndef(ignil::Reg dst, std::uint64_t addr,
                                            ignil::Block &out) const {
  ignil::Op op;
  op.opcode = ignil::Opcode::UNDEF;
  op.dst = dst;
  op.address = addr;
  out.append(std::move(op));
}

void dragon::arm::ARMIGNILLifter::emitArithFlags(
        std::uint64_t addr, ignil::Block &out, std::uint32_t &tmp,
        const std::map<ARMFlag, FlagSetter> &flagMap) const {
  const std::array<std::pair<ARMFlag, ignil::Reg>, 4> allFlags = {{
          {ARMFlag::N, regNF_},
          {ARMFlag::Z, regZF_},
          {ARMFlag::C, regCF_},
          {ARMFlag::V, regVF_},
  }};

  for (const auto &[flag, reg]: allFlags) {
    auto it = flagMap.find(flag);
    if (it != flagMap.end())
      it->second(out, tmp);
    // else: leave untouched (no UNDEF) - non-S AArch64 opcodes architecturally
    // do not affect NZCV at all, unlike x86 where every arith op does.
  }
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::zfEqZero(ignil::Value value,
                                      std::uint64_t addr) const {
  return [this, value, addr](ignil::Block &out, std::uint32_t &tmp) {
    auto t = newTemp(tmp, 1);
    out.append({ignil::Opcode::EQ,
                t,
                {value, ignil::Const{0, ignil::widthOf(value)}},
                addr});
    out.append({ignil::Opcode::COPY, regZF_, {t}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::nfSignBit(ignil::Value value,
                                       std::uint64_t addr) const {
  return [this, value, addr](ignil::Block &out, std::uint32_t &tmp) {
    auto t = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT,
                t,
                {value, ignil::Const{0, ignil::widthOf(value)}},
                addr});
    out.append({ignil::Opcode::COPY, regNF_, {t}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::cfAlwaysZero(std::uint64_t addr) const {
  return [this, addr](ignil::Block &out, std::uint32_t &) {
    out.append({ignil::Opcode::COPY, regCF_, {ignil::Const{0, 1}}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::vfAlwaysZero(std::uint64_t addr) const {
  return [this, addr](ignil::Block &out, std::uint32_t &) {
    out.append({ignil::Opcode::COPY, regVF_, {ignil::Const{0, 1}}, addr});
  };
}

dragon::arm::FlagSetter dragon::arm::ARMIGNILLifter::cfAddOverflow(
        ignil::Value result, ignil::Value addend, std::uint64_t addr) const {
  // Unsigned overflow: result wrapped around  <=>  result < addend (unsigned).
  // Same polarity as x86's CF for ADD.
  return [this, result, addend, addr](ignil::Block &out, std::uint32_t &tmp) {
    auto t = newTemp(tmp, 1);
    out.append({ignil::Opcode::ULT, t, {result, addend}, addr});
    out.append({ignil::Opcode::COPY, regCF_, {t}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::cfSubNoBorrow(ignil::Value lhs, ignil::Value rhs,
                                           std::uint64_t addr) const {
  // AArch64: C=1 means NO unsigned borrow occurred  <=>  lhs >= rhs
  // (unsigned). Opposite polarity from x86's CF for SUB (which is ULT).
  return [this, lhs, rhs, addr](ignil::Block &out, std::uint32_t &tmp) {
    auto t = newTemp(tmp, 1);
    out.append({ignil::Opcode::UGE, t, {lhs, rhs}, addr});
    out.append({ignil::Opcode::COPY, regCF_, {t}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::ofAddOverflow(ignil::Value lhs, ignil::Value rhs,
                                           ignil::Value result,
                                           std::uint64_t addr) const {
  // Signed overflow when both inputs have the same sign but the result has
  // the opposite sign.
  return [this, lhs, rhs, result, addr](ignil::Block &out, std::uint32_t &tmp) {
    ignil::Const zero{0, ignil::widthOf(lhs)};
    auto sa = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sa, {lhs, zero}, addr});
    auto sb = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sb, {rhs, zero}, addr});
    auto sr = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sr, {result, zero}, addr});
    auto sameSign = newTemp(tmp, 1);
    out.append({ignil::Opcode::EQ, sameSign, {sa, sb}, addr});
    auto diffSign = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, diffSign, {sr, sa}, addr});
    auto vf = newTemp(tmp, 1);
    out.append({ignil::Opcode::AND, vf, {sameSign, diffSign}, addr});
    out.append({ignil::Opcode::COPY, regVF_, {vf}, addr});
  };
}

dragon::arm::FlagSetter
dragon::arm::ARMIGNILLifter::ofSubOverflow(ignil::Value lhs, ignil::Value rhs,
                                           ignil::Value result,
                                           std::uint64_t addr) const {
  // Signed overflow when inputs have different signs and the result sign
  // differs from lhs.
  return [this, lhs, rhs, result, addr](ignil::Block &out, std::uint32_t &tmp) {
    ignil::Const zero{0, ignil::widthOf(lhs)};
    auto sa = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sa, {lhs, zero}, addr});
    auto sb = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sb, {rhs, zero}, addr});
    auto sr = newTemp(tmp, 1);
    out.append({ignil::Opcode::SLT, sr, {result, zero}, addr});
    auto diffAB = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, diffAB, {sa, sb}, addr});
    auto diffRA = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, diffRA, {sr, sa}, addr});
    auto vf = newTemp(tmp, 1);
    out.append({ignil::Opcode::AND, vf, {diffAB, diffRA}, addr});
    out.append({ignil::Opcode::COPY, regVF_, {vf}, addr});
  };
}

std::uint64_t
dragon::arm::ARMIGNILLifter::decodeLogicalImmediate(std::uint64_t encoded,
                                                    unsigned regSize) {
  // Standard ARM ARM "DecodeBitMasks" algorithm for the 13-bit N:immr:imms
  // encoding used by AND/ORR/EOR(S) immediate forms. Not available from any
  // public LLVM header (AArch64_AM lives in LLVM's internal target sources),
  // so reimplemented here. Verified against 6 known encodings obtained via
  // `llvm-mc -show-encoding` (0xff, 0xff00, 0xf0f0f0f0, a 32-bit-high mask,
  // #1, and a 63-bit mask) before being wired in.
  const std::uint64_t imms = encoded & 0x3F;
  const std::uint64_t immr = (encoded >> 6) & 0x3F;
  const std::uint64_t N = (encoded >> 12) & 0x1;

  // Element size comes from the position of the highest set bit of
  // (N:~imms); e.g. N=1 selects the full 64-bit element, N=0 with the top
  // bit of ~imms clear selects a 32-bit element, and so on down to 2 bits.
  const std::uint64_t combined = (N << 6) | (~imms & 0x3F);
  if (combined == 0)
    return 0; // invalid encoding

  const int len = 63 - std::countl_zero(combined);
  const unsigned size = 1u << len;
  const unsigned R = static_cast<unsigned>(immr) & (size - 1);
  const unsigned S = static_cast<unsigned>(imms) & (size - 1);

  // A run of (S+1) set bits (or all of `size` if S is at the max), to be
  // rotated right by R within the `size`-bit element.
  std::uint64_t pattern = (S == size - 1) ? ~std::uint64_t{0}
                                          : ((std::uint64_t{1} << (S + 1)) - 1);
  const std::uint64_t sizeMask =
          (size < 64) ? ((std::uint64_t{1} << size) - 1) : ~std::uint64_t{0};
  pattern &= sizeMask;
  if (R > 0)
    pattern = ((pattern >> R) | (pattern << (size - R))) & sizeMask;

  // Replicate the `size`-bit pattern to fill the full register width.
  std::uint64_t result = pattern;
  for (unsigned w = size; w < regSize; w *= 2)
    result |= result << w;

  if (regSize < 64)
    result &= (std::uint64_t{1} << regSize) - 1;
  return result;
}

dragon::ignil::Value dragon::arm::ARMIGNILLifter::emitShiftedReg(
        const llvm::MCInst &mc, unsigned regOpIdx, unsigned shiftOpIdx,
        ignil::Width width, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  auto reg = toReg(mc.getOperand(regOpIdx).getReg());
  ignil::Value base = (!reg || isZeroReg(*reg))
                              ? ignil::Value{ignil::Const{0, width}}
                              : ignil::Value{*reg};

  const auto encoded =
          static_cast<unsigned>(mc.getOperand(shiftOpIdx).getImm());
  const unsigned amount = encoded & 0x3F;
  const unsigned type = (encoded >> 6) & 0x3; // 0=LSL,1=LSR,2=ASR,3=ROR

  if (amount == 0)
    return base; // fast path - covers plain register operands, by far the
                 // most common case (includes the "mov reg,reg" ORR alias).

  auto result = newTemp(tmp, width);
  switch (type) {
    case 0:
      out.append({ignil::Opcode::SHL,
                  result,
                  {base, ignil::Const{amount, 8}},
                  addr});
      break;
    case 1:
      out.append({ignil::Opcode::SHR,
                  result,
                  {base, ignil::Const{amount, 8}},
                  addr});
      break;
    case 2:
      out.append({ignil::Opcode::SAR,
                  result,
                  {base, ignil::Const{amount, 8}},
                  addr});
      break;
    default:
      // ROR - only valid for logical (AND/ORR/EOR) shifted-register forms,
      // never ADD/SUB, and rare even there in compiler-generated code. IGNIL
      // has no rotate opcode, so be conservative and UNDEF rather than
      // silently mis-lift.
      logger_.log("emitShiftedReg: ROR shift unsupported at addr {:#x}", addr);
      out.append({ignil::Opcode::UNDEF, result, {}, addr});
      break;
  }
  return result;
}

void dragon::arm::ARMIGNILLifter::liftAddSub(const llvm::MCInst &mc,
                                             std::uint64_t addr,
                                             ignil::Block &out,
                                             std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();
  const bool isSub =
          (opc == opSUBWrr_ || opc == opSUBXrr_ || opc == opSUBWri_ ||
           opc == opSUBXri_ || opc == opSUBWrs_ || opc == opSUBXrs_ ||
           opc == opSUBSWrr_ || opc == opSUBSXrr_ || opc == opSUBSWri_ ||
           opc == opSUBSXri_ || opc == opSUBSWrs_ || opc == opSUBSXrs_);
  const bool setFlags =
          (opc == opADDSWrr_ || opc == opADDSXrr_ || opc == opADDSWri_ ||
           opc == opADDSXri_ || opc == opADDSWrs_ || opc == opADDSXrs_ ||
           opc == opSUBSWrr_ || opc == opSUBSXrr_ || opc == opSUBSWri_ ||
           opc == opSUBSXri_ || opc == opSUBSWrs_ || opc == opSUBSXrs_);
  const bool isImmForm =
          (opc == opADDWri_ || opc == opADDXri_ || opc == opADDSWri_ ||
           opc == opADDSXri_ || opc == opSUBWri_ || opc == opSUBXri_ ||
           opc == opSUBSWri_ || opc == opSUBSXri_);
  const bool isShiftedForm =
          (opc == opADDWrs_ || opc == opADDXrs_ || opc == opADDSWrs_ ||
           opc == opADDSXrs_ || opc == opSUBWrs_ || opc == opSUBXrs_ ||
           opc == opSUBSWrs_ || opc == opSUBSXrs_);

  // op[0]=dst, op[1]=Rn(lhs) - AArch64 ADD/SUB is 3-address, unlike x86's
  // tied dst/src1, so there is no "save dst before overwrite" step here.
  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftAddSub in addr {:#x} no dst", addr);
    return;
  }
  auto lhsReg = toReg(mc.getOperand(1).getReg());
  if (!lhsReg) {
    logger_.log("Error liftAddSub in addr {:#x} no lhs", addr);
    emitUndef(*dst, addr, out);
    return;
  }
  ignil::Value lhs = isZeroReg(*lhsReg)
                             ? ignil::Value{ignil::Const{0, dst->width}}
                             : ignil::Value{*lhsReg};

  ignil::Value rhs;
  if (isImmForm) {
    // op[2]=12-bit imm, op[3]=shift (0 or 12, meaning imm<<12).
    auto imm = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
    auto shift = static_cast<std::uint64_t>(mc.getOperand(3).getImm());
    rhs = ignil::Const{imm << shift, dst->width};
  } else if (isShiftedForm) {
    rhs = emitShiftedReg(mc, 2, 3, dst->width, addr, out, tmp);
  } else {
    auto rhsReg = toReg(mc.getOperand(2).getReg());
    rhs = (!rhsReg || isZeroReg(*rhsReg))
                  ? ignil::Value{ignil::Const{0, dst->width}}
                  : ignil::Value{*rhsReg};
  }

  auto result = newTemp(tmp, dst->width);
  out.append({isSub ? ignil::Opcode::SUB : ignil::Opcode::ADD,
              result,
              {lhs, rhs},
              addr});

  // A write to XZR/WZR is architecturally discarded - this is exactly what
  // makes CMP (SUBS, Rd=zero) and CMN (ADDS, Rd=zero) fall out of this same
  // generic function for free, with no dedicated liftCmp needed.
  if (!isZeroReg(*dst))
    out.append({ignil::Opcode::COPY, *dst, {result}, addr});

  // Only S-suffixed opcodes touch NZCV at all; plain ADD/SUB leave flags
  // completely untouched (no Op emitted), unlike x86 where every arith op
  // affects EFLAGS.
  if (setFlags) {
    if (isSub)
      emitArithFlags(
              addr, out, tmp,
              {
                      {ARMFlag::C, cfSubNoBorrow(lhs, rhs, addr)},
                      {ARMFlag::Z, zfEqZero(result, addr)},
                      {ARMFlag::N, nfSignBit(result, addr)},
                      {ARMFlag::V, ofSubOverflow(lhs, rhs, result, addr)},
              });
    else
      emitArithFlags(
              addr, out, tmp,
              {
                      {ARMFlag::C, cfAddOverflow(result, rhs, addr)},
                      {ARMFlag::Z, zfEqZero(result, addr)},
                      {ARMFlag::N, nfSignBit(result, addr)},
                      {ARMFlag::V, ofAddOverflow(lhs, rhs, result, addr)},
              });
  }
}

void dragon::arm::ARMIGNILLifter::liftLogic(const llvm::MCInst &mc,
                                            std::uint64_t addr,
                                            ignil::Block &out,
                                            std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  ignil::Opcode irOp;
  if (opc == opANDWrr_ || opc == opANDXrr_ || opc == opANDWri_ ||
      opc == opANDXri_ || opc == opANDWrs_ || opc == opANDXrs_ ||
      opc == opANDSWri_ || opc == opANDSXri_ || opc == opANDSWrs_ ||
      opc == opANDSXrs_)
    irOp = ignil::Opcode::AND;
  else if (opc == opORRWrr_ || opc == opORRXrr_ || opc == opORRWri_ ||
           opc == opORRXri_ || opc == opORRWrs_ || opc == opORRXrs_)
    irOp = ignil::Opcode::OR;
  else
    irOp = ignil::Opcode::XOR;

  // Only AND has S-suffixed forms (ANDS) - ORR/EOR never set flags at all,
  // and (per the constructor's opcode table) AArch64 has no ANDSWrr/ANDSXrr,
  // only the ri/rs S-forms.
  const bool setFlags = (opc == opANDSWri_ || opc == opANDSXri_ ||
                         opc == opANDSWrs_ || opc == opANDSXrs_);
  const bool isImmForm =
          (opc == opANDWri_ || opc == opANDXri_ || opc == opANDSWri_ ||
           opc == opANDSXri_ || opc == opORRWri_ || opc == opORRXri_ ||
           opc == opEORWri_ || opc == opEORXri_);
  const bool isPlainRr =
          (opc == opANDWrr_ || opc == opANDXrr_ || opc == opORRWrr_ ||
           opc == opORRXrr_ || opc == opEORWrr_ || opc == opEORXrr_);

  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftLogic in addr {:#x} no dst", addr);
    return;
  }
  auto lhsReg = toReg(mc.getOperand(1).getReg());
  if (!lhsReg) {
    logger_.log("Error liftLogic in addr {:#x} no lhs", addr);
    emitUndef(*dst, addr, out);
    return;
  }
  ignil::Value lhs = isZeroReg(*lhsReg)
                             ? ignil::Value{ignil::Const{0, dst->width}}
                             : ignil::Value{*lhsReg};

  ignil::Value rhs;
  if (isImmForm) {
    auto encoded = static_cast<std::uint64_t>(mc.getOperand(2).getImm());
    auto decoded = decodeLogicalImmediate(encoded, dst->width);
    rhs = ignil::Const{decoded, dst->width};
  } else if (isPlainRr) {
    auto rhsReg = toReg(mc.getOperand(2).getReg());
    rhs = (!rhsReg || isZeroReg(*rhsReg))
                  ? ignil::Value{ignil::Const{0, dst->width}}
                  : ignil::Value{*rhsReg};
  } else {
    // rs form - also where the "mov reg,reg" ORR alias (Rn=XZR, shift=0)
    // falls out for free via the lhs zero-reg handling above.
    rhs = emitShiftedReg(mc, 2, 3, dst->width, addr, out, tmp);
  }

  auto result = newTemp(tmp, dst->width);
  out.append({irOp, result, {lhs, rhs}, addr});

  // Discarded write covers TST (ANDS, Rd=zero); MOV (ORR, Rn=XZR) already
  // has a real dst so it takes this branch normally.
  if (!isZeroReg(*dst))
    out.append({ignil::Opcode::COPY, *dst, {result}, addr});

  if (setFlags)
    // ANDS: C and V are architecturally hardwired to 0 (logical ops never
    // carry/overflow); only Z/N are actually computed from the result.
    emitArithFlags(addr, out, tmp,
                   {
                           {ARMFlag::C, cfAlwaysZero(addr)},
                           {ARMFlag::Z, zfEqZero(result, addr)},
                           {ARMFlag::N, nfSignBit(result, addr)},
                           {ARMFlag::V, vfAlwaysZero(addr)},
                   });
}

dragon::ignil::Temp dragon::arm::ARMIGNILLifter::emitAddress(
        const llvm::MCInst &mc, unsigned opStart, std::int64_t scale,
        ignil::Width ptrWidth, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  // mc.getOperand(opStart)=base register, mc.getOperand(opStart+1)=offset
  // immediate. Reused for LDR/STR *ui (scale=element size), single LDR/STR
  // pre/post (scale=1, immediate already byte-granular), and LDP/STP in all
  // three forms (scale=element size - LDP/STP immediates are always scaled,
  // unlike single-register pre/post).
  auto base = toReg(mc.getOperand(opStart).getReg());
  auto imm = mc.getOperand(opStart + 1).getImm();

  ignil::Value baseVal = (!base || isZeroReg(*base))
                                 ? ignil::Value{ignil::Const{0, ptrWidth}}
                                 : ignil::Value{*base};

  auto result = newTemp(tmp, ptrWidth);
  if (imm == 0) {
    out.append({ignil::Opcode::COPY, result, {baseVal}, addr});
    return result;
  }

  const auto offset = static_cast<std::uint64_t>(imm * scale);
  out.append({ignil::Opcode::ADD,
              result,
              {baseVal, ignil::Const{offset, ptrWidth}},
              addr});
  return result;
}

void dragon::arm::ARMIGNILLifter::liftLoad(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width memWidth;
  std::int64_t scale;
  bool signExtend = false;
  bool isPrePost = false;
  bool isPost = false;

  if (opc == opLDRWui_) {
    memWidth = 32;
    scale = 4;
  } else if (opc == opLDRXui_) {
    memWidth = 64;
    scale = 8;
  } else if (opc == opLDRBui_ || opc == opLDRBBui_) {
    memWidth = 8;
    scale = 1;
  } else if (opc == opLDRHui_ || opc == opLDRHHui_) {
    memWidth = 16;
    scale = 2;
  } else if (opc == opLDRSBWui_ || opc == opLDRSBXui_) {
    memWidth = 8;
    scale = 1;
    signExtend = true;
  } else if (opc == opLDRSHWui_ || opc == opLDRSHXui_) {
    memWidth = 16;
    scale = 2;
    signExtend = true;
  } else if (opc == opLDRSWui_) {
    memWidth = 32;
    scale = 4;
    signExtend = true;
  } else if (opc == opLDRWpre_ || opc == opLDRWpost_) {
    memWidth = 32;
    scale = 1; // single-register pre/post immediate is raw bytes, not scaled
    isPrePost = true;
    isPost = (opc == opLDRWpost_);
  } else if (opc == opLDRXpre_ || opc == opLDRXpost_) {
    memWidth = 64;
    scale = 1;
    isPrePost = true;
    isPost = (opc == opLDRXpost_);
  } else {
    logger_.log("Error liftLoad in addr {:#x} unhandled opcode", addr);
    return;
  }

  // *ui: op[0]=dst, op[1]=Rn, op[2]=imm. pre/post: op[0]=writeback(=Rn),
  // op[1]=dst, op[2]=Rn, op[3]=imm.
  const unsigned dstOpIdx = isPrePost ? 1 : 0;
  const unsigned baseOpIdx = isPrePost ? 2 : 1;

  auto dst = toReg(mc.getOperand(dstOpIdx).getReg());
  if (!dst) {
    logger_.log("Error liftLoad in addr {:#x} no dst", addr);
    return;
  }

  constexpr ignil::Width ptrWidth = 64; // AArch64 pointers are always 64-bit
  ignil::Temp loadAddr;
  ignil::Temp writebackAddr;

  if (isPrePost) {
    if (isPost) {
      // Post-index: the transfer uses the base as-is; the writeback address
      // (base+offset) is computed separately and only applied afterward.
      auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
      if (!baseReg) {
        logger_.log("Error liftLoad in addr {:#x} no base", addr);
        emitUndef(*dst, addr, out);
        return;
      }
      loadAddr = newTemp(tmp, ptrWidth);
      out.append({ignil::Opcode::COPY, loadAddr, {*baseReg}, addr});
      writebackAddr =
              emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
    } else {
      // Pre-index: the transfer address IS base+offset, which is also
      // exactly the value written back afterward.
      loadAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
      writebackAddr = loadAddr;
    }
  } else {
    loadAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
  }

  auto loaded = newTemp(tmp, memWidth);
  out.append({ignil::Opcode::LOAD, loaded, {loadAddr}, addr});

  if (memWidth < dst->width) {
    auto extended = newTemp(tmp, dst->width);
    out.append({signExtend ? ignil::Opcode::SEXT : ignil::Opcode::ZEXT,
                extended,
                {loaded},
                addr});
    loaded = extended;
  }

  if (!isZeroReg(*dst))
    out.append({ignil::Opcode::COPY, *dst, {loaded}, addr});

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftStore(const llvm::MCInst &mc,
                                            std::uint64_t addr,
                                            ignil::Block &out,
                                            std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width memWidth;
  std::int64_t scale;
  bool isPrePost = false;
  bool isPost = false;

  if (opc == opSTRWui_) {
    memWidth = 32;
    scale = 4;
  } else if (opc == opSTRXui_) {
    memWidth = 64;
    scale = 8;
  } else if (opc == opSTRBui_ || opc == opSTRBBui_) {
    memWidth = 8;
    scale = 1;
  } else if (opc == opSTRHui_ || opc == opSTRHHui_) {
    memWidth = 16;
    scale = 2;
  } else if (opc == opSTRWpre_ || opc == opSTRWpost_) {
    memWidth = 32;
    scale = 1;
    isPrePost = true;
    isPost = (opc == opSTRWpost_);
  } else if (opc == opSTRXpre_ || opc == opSTRXpost_) {
    memWidth = 64;
    scale = 1;
    isPrePost = true;
    isPost = (opc == opSTRXpost_);
  } else {
    logger_.log("Error liftStore in addr {:#x} unhandled opcode", addr);
    return;
  }

  // *ui: op[0]=Rt(src), op[1]=Rn, op[2]=imm. pre/post: op[0]=writeback(=Rn),
  // op[1]=Rt(src), op[2]=Rn, op[3]=imm.
  const unsigned srcOpIdx = isPrePost ? 1 : 0;
  const unsigned baseOpIdx = isPrePost ? 2 : 1;

  auto srcReg = toReg(mc.getOperand(srcOpIdx).getReg());
  if (!srcReg) {
    logger_.log("Error liftStore in addr {:#x} no src", addr);
    return;
  }

  ignil::Value src = isZeroReg(*srcReg)
                             ? ignil::Value{ignil::Const{0, memWidth}}
                             : ignil::Value{*srcReg};
  if (srcReg->width > memWidth) {
    auto truncated = newTemp(tmp, memWidth);
    out.append({ignil::Opcode::TRUNC, truncated, {src}, addr});
    src = truncated;
  }

  constexpr ignil::Width ptrWidth = 64;
  ignil::Temp storeAddr;
  ignil::Temp writebackAddr;

  if (isPrePost) {
    if (isPost) {
      auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
      if (!baseReg) {
        logger_.log("Error liftStore in addr {:#x} no base", addr);
        return;
      }
      storeAddr = newTemp(tmp, ptrWidth);
      out.append({ignil::Opcode::COPY, storeAddr, {*baseReg}, addr});
      writebackAddr =
              emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
    } else {
      storeAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
      writebackAddr = storeAddr;
    }
  } else {
    storeAddr = emitAddress(mc, baseOpIdx, scale, ptrWidth, addr, out, tmp);
  }

  out.append({ignil::Opcode::STORE, std::nullopt, {storeAddr, src}, addr});

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseOpIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftLoadPair(const llvm::MCInst &mc,
                                               std::uint64_t addr,
                                               ignil::Block &out,
                                               std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width elemWidth;
  std::int64_t scale;
  bool isPre = false;
  bool isPost = false;

  if (opc == opLDPWi_) {
    elemWidth = 32;
    scale = 4;
  } else if (opc == opLDPXi_) {
    elemWidth = 64;
    scale = 8;
  } else if (opc == opLDPWpre_) {
    elemWidth = 32;
    scale = 4;
    isPre = true;
  } else if (opc == opLDPXpre_) {
    elemWidth = 64;
    scale = 8;
    isPre = true;
  } else if (opc == opLDPWpost_) {
    elemWidth = 32;
    scale = 4;
    isPost = true;
  } else if (opc == opLDPXpost_) {
    elemWidth = 64;
    scale = 8;
    isPost = true;
  } else {
    logger_.log("Error liftLoadPair in addr {:#x} unhandled opcode", addr);
    return;
  }

  const bool isPrePost = isPre || isPost;
  // offset form: op[0]=Rt1, op[1]=Rt2, op[2]=Rn, op[3]=imm.
  // pre/post form: op[0]=writeback(=Rn), op[1]=Rt1, op[2]=Rt2, op[3]=Rn,
  // op[4]=imm.
  const unsigned rt1Idx = isPrePost ? 1 : 0;
  const unsigned rt2Idx = isPrePost ? 2 : 1;
  const unsigned baseIdx = isPrePost ? 3 : 2;

  auto rt1 = toReg(mc.getOperand(rt1Idx).getReg());
  auto rt2 = toReg(mc.getOperand(rt2Idx).getReg());
  if (!rt1 || !rt2) {
    logger_.log("Error liftLoadPair in addr {:#x} bad Rt1/Rt2", addr);
    return;
  }

  constexpr ignil::Width ptrWidth = 64;
  ignil::Temp loadAddr;
  ignil::Temp writebackAddr;

  if (isPost) {
    // LDP/STP immediates are always scaled by element size, in all three
    // forms - unlike single LDR/STR, where only the *ui (offset) form is
    // scaled and pre/post are raw bytes. Post here still uses the base
    // as-is for the transfer; only the writeback is offset.
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (!baseReg) {
      logger_.log("Error liftLoadPair in addr {:#x} no base", addr);
      return;
    }
    loadAddr = newTemp(tmp, ptrWidth);
    out.append({ignil::Opcode::COPY, loadAddr, {*baseReg}, addr});
    writebackAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  } else if (isPre) {
    loadAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
    writebackAddr = loadAddr;
  } else {
    loadAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  }

  const auto elemBytes = static_cast<std::uint64_t>(elemWidth / 8);

  auto loaded1 = newTemp(tmp, elemWidth);
  out.append({ignil::Opcode::LOAD, loaded1, {loadAddr}, addr});
  if (!isZeroReg(*rt1))
    out.append({ignil::Opcode::COPY, *rt1, {loaded1}, addr});

  auto addr2 = newTemp(tmp, ptrWidth);
  out.append({ignil::Opcode::ADD,
              addr2,
              {loadAddr, ignil::Const{elemBytes, ptrWidth}},
              addr});
  auto loaded2 = newTemp(tmp, elemWidth);
  out.append({ignil::Opcode::LOAD, loaded2, {addr2}, addr});
  if (!isZeroReg(*rt2))
    out.append({ignil::Opcode::COPY, *rt2, {loaded2}, addr});

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftStorePair(const llvm::MCInst &mc,
                                                std::uint64_t addr,
                                                ignil::Block &out,
                                                std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  ignil::Width elemWidth;
  std::int64_t scale;
  bool isPre = false;
  bool isPost = false;

  if (opc == opSTPWi_) {
    elemWidth = 32;
    scale = 4;
  } else if (opc == opSTPXi_) {
    elemWidth = 64;
    scale = 8;
  } else if (opc == opSTPWpre_) {
    elemWidth = 32;
    scale = 4;
    isPre = true;
  } else if (opc == opSTPXpre_) {
    elemWidth = 64;
    scale = 8;
    isPre = true;
  } else if (opc == opSTPWpost_) {
    elemWidth = 32;
    scale = 4;
    isPost = true;
  } else if (opc == opSTPXpost_) {
    elemWidth = 64;
    scale = 8;
    isPost = true;
  } else {
    logger_.log("Error liftStorePair in addr {:#x} unhandled opcode", addr);
    return;
  }

  const bool isPrePost = isPre || isPost;
  const unsigned rt1Idx = isPrePost ? 1 : 0;
  const unsigned rt2Idx = isPrePost ? 2 : 1;
  const unsigned baseIdx = isPrePost ? 3 : 2;

  auto rt1 = toReg(mc.getOperand(rt1Idx).getReg());
  auto rt2 = toReg(mc.getOperand(rt2Idx).getReg());
  if (!rt1 || !rt2) {
    logger_.log("Error liftStorePair in addr {:#x} bad Rt1/Rt2", addr);
    return;
  }
  ignil::Value v1 = isZeroReg(*rt1) ? ignil::Value{ignil::Const{0, elemWidth}}
                                    : ignil::Value{*rt1};
  ignil::Value v2 = isZeroReg(*rt2) ? ignil::Value{ignil::Const{0, elemWidth}}
                                    : ignil::Value{*rt2};

  constexpr ignil::Width ptrWidth = 64;
  ignil::Temp storeAddr;
  ignil::Temp writebackAddr;

  if (isPost) {
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (!baseReg) {
      logger_.log("Error liftStorePair in addr {:#x} no base", addr);
      return;
    }
    storeAddr = newTemp(tmp, ptrWidth);
    out.append({ignil::Opcode::COPY, storeAddr, {*baseReg}, addr});
    writebackAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  } else if (isPre) {
    storeAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
    writebackAddr = storeAddr;
  } else {
    storeAddr = emitAddress(mc, baseIdx, scale, ptrWidth, addr, out, tmp);
  }

  const auto elemBytes = static_cast<std::uint64_t>(elemWidth / 8);

  out.append({ignil::Opcode::STORE, std::nullopt, {storeAddr, v1}, addr});
  auto addr2 = newTemp(tmp, ptrWidth);
  out.append({ignil::Opcode::ADD,
              addr2,
              {storeAddr, ignil::Const{elemBytes, ptrWidth}},
              addr});
  out.append({ignil::Opcode::STORE, std::nullopt, {addr2, v2}, addr});

  if (isPrePost) {
    auto baseReg = toReg(mc.getOperand(baseIdx).getReg());
    if (baseReg)
      out.append({ignil::Opcode::COPY, *baseReg, {writebackAddr}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftAdr(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();

  auto dst = toReg(mc.getOperand(0).getReg());
  if (!dst) {
    logger_.log("Error liftAdr in addr {:#x} no dst", addr);
    return;
  }

  const auto imm = mc.getOperand(1).getImm();
  std::uint64_t value;
  if (opc == opADRP_) {
    // ADRP: Rd = (PC & ~0xFFF) + imm*0x1000. The base is the *page-aligned*
    // instruction address, not the raw address - critical and easy to miss,
    // since ADRP is almost never itself sitting on a 4K boundary.
    const std::uint64_t page = addr & ~std::uint64_t{0xFFF};
    value = page + static_cast<std::uint64_t>(imm) * 0x1000;
  } else {
    // ADR: Rd = PC + imm, byte-precise, no alignment.
    value = addr + static_cast<std::uint64_t>(imm);
  }

  if (isZeroReg(*dst))
    return;

  out.append(
          {ignil::Opcode::COPY, *dst, {ignil::Const{value, dst->width}}, addr});
}

dragon::ignil::Temp dragon::arm::ARMIGNILLifter::emitCondition(
        unsigned condCode, std::uint64_t addr, ignil::Block &out,
        std::uint32_t &tmp) const {
  // AArch64CC::CondCode enum (AArch64BaseInfo.h):
  //   0=EQ,1=NE,2=CS/HS,3=CC/LO,4=MI,5=PL,6=VS,7=VC,
  //   8=HI,9=LS,10=GE,11=LT,12=GT,13=LE,14=AL,15=NV
  auto flagSet = [&](ignil::Reg flag) -> ignil::Temp {
    auto t = newTemp(tmp, 8);
    out.append({ignil::Opcode::COPY, t, {flag}, addr});
    auto cond = newTemp(tmp, 1);
    out.append({ignil::Opcode::NEQ, cond, {t, ignil::Const{0, 8}}, addr});
    return cond;
  };
  auto flagClear = [&](ignil::Reg flag) -> ignil::Temp {
    auto t = newTemp(tmp, 8);
    out.append({ignil::Opcode::COPY, t, {flag}, addr});
    auto cond = newTemp(tmp, 1);
    out.append({ignil::Opcode::EQ, cond, {t, ignil::Const{0, 8}}, addr});
    return cond;
  };
  auto readFlag = [&](ignil::Reg flag) -> ignil::Temp {
    auto t = newTemp(tmp, 8);
    out.append({ignil::Opcode::COPY, t, {flag}, addr});
    return t;
  };

  switch (condCode) {
    case 0:
      return flagSet(regZF_); // EQ: Z=1
    case 1:
      return flagClear(regZF_); // NE: Z=0
    case 2:
      return flagSet(regCF_); // CS/HS: C=1
    case 3:
      return flagClear(regCF_); // CC/LO: C=0
    case 4:
      return flagSet(regNF_); // MI: N=1
    case 5:
      return flagClear(regNF_); // PL: N=0
    case 6:
      return flagSet(regVF_); // VS: V=1
    case 7:
      return flagClear(regVF_); // VC: V=0
    case 8: { // HI: C=1 AND Z=0
      auto c = flagSet(regCF_), zClr = flagClear(regZF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::AND, cond, {c, zClr}, addr});
      return cond;
    }
    case 9: { // LS: C=0 OR Z=1
      auto cClr = flagClear(regCF_), z = flagSet(regZF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::OR, cond, {cClr, z}, addr});
      return cond;
    }
    case 10: { // GE: N==V
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::EQ, cond, {n, v}, addr});
      return cond;
    }
    case 11: { // LT: N!=V
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::NEQ, cond, {n, v}, addr});
      return cond;
    }
    case 12: { // GT: Z=0 AND N==V
      auto zClr = flagClear(regZF_);
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto nEqV = newTemp(tmp, 1);
      out.append({ignil::Opcode::EQ, nEqV, {n, v}, addr});
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::AND, cond, {zClr, nEqV}, addr});
      return cond;
    }
    case 13: { // LE: Z=1 OR N!=V
      auto z = flagSet(regZF_);
      auto n = readFlag(regNF_), v = readFlag(regVF_);
      auto nNeV = newTemp(tmp, 1);
      out.append({ignil::Opcode::NEQ, nNeV, {n, v}, addr});
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::OR, cond, {z, nNeV}, addr});
      return cond;
    }
    case 14:
    case 15: { // AL, NV - always taken (NV is reserved, treated as AL)
      auto cond = newTemp(tmp, 1);
      out.append({ignil::Opcode::COPY, cond, {ignil::Const{1, 1}}, addr});
      return cond;
    }
    default: {
      auto undef = newTemp(tmp, 1);
      out.append({ignil::Opcode::UNDEF, undef, {}, addr});
      return undef;
    }
  }
}

void dragon::arm::ARMIGNILLifter::liftBcc(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  // op[0]=condition code (imm), op[1]=target (imm, instruction-count units,
  // relative to this instruction's own address - not addr+size, and not
  // byte-scaled). Verified via llvm-mc -disassemble -show-inst.
  const auto condCode = static_cast<unsigned>(mc.getOperand(0).getImm());
  const auto offsetUnits = mc.getOperand(1).getImm();
  const auto taken = static_cast<std::uint64_t>(
          static_cast<std::int64_t>(addr) + offsetUnits * 4);
  const std::uint64_t fallthrough = addr + 4; // AArch64 insns are fixed 4B

  auto cond = emitCondition(condCode, addr, out, tmp);
  out.append({ignil::Opcode::CJMP,
              std::nullopt,
              {cond, ignil::Const{taken, 64}, ignil::Const{fallthrough, 64}},
              addr});
}

void dragon::arm::ARMIGNILLifter::liftCbz(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();
  const bool isNonZero = (opc == opCBNZW_ || opc == opCBNZX_);
  const ignil::Width width = (opc == opCBZW_ || opc == opCBNZW_) ? 32 : 64;

  // op[0]=Rt, op[1]=target (same instruction-count/own-address convention as
  // Bcc above).
  auto rt = toReg(mc.getOperand(0).getReg());
  const auto offsetUnits = mc.getOperand(1).getImm();
  const auto taken = static_cast<std::uint64_t>(
          static_cast<std::int64_t>(addr) + offsetUnits * 4);
  const std::uint64_t fallthrough = addr + 4;

  ignil::Value val = (!rt || isZeroReg(*rt))
                             ? ignil::Value{ignil::Const{0, width}}
                             : ignil::Value{*rt};
  auto cond = newTemp(tmp, 1);
  out.append({isNonZero ? ignil::Opcode::NEQ : ignil::Opcode::EQ,
              cond,
              {val, ignil::Const{0, width}},
              addr});
  out.append({ignil::Opcode::CJMP,
              std::nullopt,
              {cond, ignil::Const{taken, 64}, ignil::Const{fallthrough, 64}},
              addr});
}

void dragon::arm::ARMIGNILLifter::liftTbz(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  const unsigned opc = mc.getOpcode();
  const bool isNonZero = (opc == opTBNZW_ || opc == opTBNZX_);
  const ignil::Width width = (opc == opTBZW_ || opc == opTBNZW_) ? 32 : 64;

  // op[0]=Rt, op[1]=bit number, op[2]=target (same convention as Bcc/CBZ).
  auto rt = toReg(mc.getOperand(0).getReg());
  const auto bitNum = static_cast<std::uint64_t>(mc.getOperand(1).getImm());
  const auto offsetUnits = mc.getOperand(2).getImm();
  const auto taken = static_cast<std::uint64_t>(
          static_cast<std::int64_t>(addr) + offsetUnits * 4);
  const std::uint64_t fallthrough = addr + 4;

  ignil::Value val = (!rt || isZeroReg(*rt))
                             ? ignil::Value{ignil::Const{0, width}}
                             : ignil::Value{*rt};
  auto masked = newTemp(tmp, width);
  out.append({ignil::Opcode::AND,
              masked,
              {val, ignil::Const{std::uint64_t{1} << bitNum, width}},
              addr});
  auto cond = newTemp(tmp, 1);
  out.append({isNonZero ? ignil::Opcode::NEQ : ignil::Opcode::EQ,
              cond,
              {masked, ignil::Const{0, width}},
              addr});
  out.append({ignil::Opcode::CJMP,
              std::nullopt,
              {cond, ignil::Const{taken, 64}, ignil::Const{fallthrough, 64}},
              addr});
}

void dragon::arm::ARMIGNILLifter::liftBranch(const llvm::MCInst &mc,
                                             std::uint64_t addr,
                                             ignil::Block &out,
                                             std::uint32_t &tmp) const {
  // B: single imm operand (instruction-count units, own-address relative).
  // BR: single register operand (indirect).
  const auto &op = mc.getOperand(0);
  if (op.isImm()) {
    const auto target = static_cast<std::uint64_t>(
            static_cast<std::int64_t>(addr) + op.getImm() * 4);
    out.append({ignil::Opcode::JMP,
                std::nullopt,
                {ignil::Const{target, 64}},
                addr});
  } else if (op.isReg()) {
    auto targetReg = toReg(op.getReg());
    if (!targetReg) {
      logger_.log("Error liftBranch in addr {:#x} no target register", addr);
      return;
    }
    out.append({ignil::Opcode::JMP, std::nullopt, {*targetReg}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftCall(const llvm::MCInst &mc,
                                           std::uint64_t addr,
                                           ignil::Block &out,
                                           std::uint32_t &tmp) const {
  // BL: single imm operand (instruction-count units, own-address relative).
  // BLR: single register operand (indirect).
  const auto &op = mc.getOperand(0);
  if (op.isImm()) {
    const auto target = static_cast<std::uint64_t>(
            static_cast<std::int64_t>(addr) + op.getImm() * 4);
    out.append({ignil::Opcode::CALL,
                std::nullopt,
                {ignil::Const{target, 64}},
                addr});
  } else if (op.isReg()) {
    auto targetReg = toReg(op.getReg());
    if (!targetReg) {
      logger_.log("Error liftCall in addr {:#x} no target register", addr);
      return;
    }
    out.append({ignil::Opcode::CALL, std::nullopt, {*targetReg}, addr});
  }
}

void dragon::arm::ARMIGNILLifter::liftRet(const llvm::MCInst &mc,
                                          std::uint64_t addr, ignil::Block &out,
                                          std::uint32_t &tmp) const {
  // Both RET (explicit register operand) and RET_ReallyLR (implicit LR)
  // are plain returns for intra-function IGNIL purposes - the target
  // register is always LR in practice, and control simply transfers back
  // to the caller.
  out.append({ignil::Opcode::RET, std::nullopt, {}, addr});
}
